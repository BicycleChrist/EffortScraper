#!/usr/bin/env python3
"""
NHL Analytics Database Manager

This module handles the creation and population of the NHL analytics database
from CSV files generated by the NST scraper.

Design principles:
- Normalized schema for data integrity
- Optimized for analytical queries and simulations
- Handles incremental updates
- Type safety and data validation
"""

import sqlite3
import csv
import os
import re
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Tuple, Optional, Any
from dataclasses import dataclass


@dataclass
class GameInfo:
    """Parsed game information from filename"""
    away_team: str
    home_team: str
    nst_game_id: str
    team_name: str
    category: str
    situation: str


class NHLDatabaseManager:
    """Manages the NHL analytics SQLite database"""

    def __init__(self, db_path: str = "nhl_analytics.db", player_ids_file: str = "player_ids.txt"):
        """
        Initialize database manager

        Args:
            db_path: Path to SQLite database file
            player_ids_file: Path to player IDs mapping file
        """
        self.db_path = db_path
        self.player_ids_file = player_ids_file
        self.conn: Optional[sqlite3.Connection] = None
        self.cursor: Optional[sqlite3.Cursor] = None

        # Mapping of situation codes to IDs (loaded from DB)
        self.situation_map: Dict[str, int] = {}
        self.team_map: Dict[str, int] = {}
        self.player_map: Dict[Tuple[str, str], str] = {}  # (name, position) -> nhl_player_id

        # NHL player ID mapping (name -> nhl_id)
        self.nhl_player_ids: Dict[str, str] = {}
        self._load_nhl_player_ids()

    def _load_nhl_player_ids(self):
        """Load NHL player IDs from file"""
        if not os.path.exists(self.player_ids_file):
            print(f"Warning: {self.player_ids_file} not found. Player IDs will not be mapped.")
            return

        with open(self.player_ids_file, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if ':' in line:
                    parts = line.rsplit(':', 1)
                    if len(parts) == 2:
                        name = parts[0].strip()
                        nhl_id = parts[1].strip()
                        self.nhl_player_ids[name] = nhl_id

        print(f"Loaded {len(self.nhl_player_ids)} NHL player ID mappings")

    def connect(self):
        """Connect to database"""
        self.conn = sqlite3.connect(self.db_path)
        self.cursor = self.conn.cursor()

    def disconnect(self):
        """Disconnect from database"""
        if self.conn:
            self.conn.close()
            self.conn = None
            self.cursor = None

    def __enter__(self):
        """Context manager entry"""
        self.connect()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        """Context manager exit"""
        self.disconnect()

    def initialize_database(self, schema_path: str = "nhl_analytics_schema.sql"):
        """
        Initialize database with schema

        Args:
            schema_path: Path to SQL schema file
        """
        if not self.conn:
            raise RuntimeError("Not connected to database")

        with open(schema_path, 'r') as f:
            schema_sql = f.read()

        # Execute schema - split on semicolons but handle them in strings
        statements = schema_sql.split(';')
        for statement in statements:
            statement = statement.strip()
            if statement:
                try:
                    self.cursor.execute(statement)
                except sqlite3.Error as e:
                    print(f"Error executing statement: {e}")
                    print(f"Statement: {statement[:100]}...")

        self.conn.commit()
        print(f"Database initialized at {self.db_path}")

