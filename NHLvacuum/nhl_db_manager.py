    def get_or_create_team(self, team_abbr: str) -> int:
        """
        Get team ID from pre-populated teams table

        Args:
            team_abbr: Team abbreviation (e.g., 'OTT', 'BOS')

        Returns:
            Team ID
        """
        # Check cache first
        if team_abbr in self.team_map:
            return self.team_map[team_abbr]

        # Reload team map if not found
        self.cursor.execute("SELECT team_id, team_abbr FROM teams")
        self.team_map = {abbr: tid for tid, abbr in self.cursor.fetchall()}

        if team_abbr in self.team_map:
            return self.team_map[team_abbr]

        # This shouldn't happen if teams are pre-populated correctly
        raise ValueError(f"Team abbreviation '{team_abbr}' not found in teams table. Please add it to populate_reference_data().")

    def get_or_create_player(self, player_name: str, position: str) -> str:
        """
        Get player ID or create if doesn't exist

        Args:
            player_name: Player's name
            position: Player position (C, L, R, D, G)

        Returns:
            NHL Player ID (string)
        """
        # Normalize player name (replace non-breaking spaces with regular spaces)
        player_name = player_name.replace('\xa0', ' ').replace('\u00a0', ' ').strip()

        key = (player_name, position)
        if key in self.player_map:
            return self.player_map[key]

        # Get NHL player ID from mapping, or generate a placeholder
        nhl_player_id = self.nhl_player_ids.get(player_name)

        if not nhl_player_id:
            # If not found, create a placeholder ID (use negative numbers)
            nhl_player_id = f"UNKNOWN_{abs(hash(player_name)) % 1000000}"
            # Only print first few warnings to avoid spam
            if len([k for k in self.player_map.keys() if 'UNKNOWN' in str(self.player_map[k])]) < 5:
                print(f"Warning: No NHL ID found for '{player_name}' ({position}), using {nhl_player_id}")
                print(f"  Debug: Name length={len(player_name)}, repr={repr(player_name)}")

        # Try to get existing
        self.cursor.execute(
            "SELECT player_id FROM players WHERE player_id = ?",
            (nhl_player_id,)
        )
        result = self.cursor.fetchone()

        if not result:
            # Create new player
            self.cursor.execute(
                "INSERT INTO players (player_id, player_name, position) VALUES (?, ?, ?)",
                (nhl_player_id, player_name, position)
            )
            self.conn.commit()

        self.player_map[key] = nhl_player_id
        return nhl_player_id

    def get_or_create_game(self, game_info: GameInfo, game_date: str, season: str = None) -> str:
        """
        Get game ID or create if doesn't exist

        Args:
            game_info: Parsed game information
            game_date: Date of game (YYYY-MM-DD)
            season: Season string (e.g., '2024-2025')

        Returns:
            Game ID (TEXT - the actual NHL game ID)
        """
        game_id = game_info.nst_game_id

        # Try to get existing game
        self.cursor.execute(
            "SELECT game_id FROM games WHERE game_id = ?",
            (game_id,)
        )
        result = self.cursor.fetchone()

        if result:
            return result[0]

        # Create new game
        home_team_id = self.get_or_create_team(game_info.home_team)
        away_team_id = self.get_or_create_team(game_info.away_team)

        # Derive season from date if not provided
        if season is None:
            date_obj = datetime.strptime(game_date, '%Y-%m-%d')
            year = date_obj.year
            # NHL season spans two years, starts in October
            if date_obj.month >= 10:
                season = f"{year}-{year + 1}"
            else:
                season = f"{year - 1}-{year}"

        self.cursor.execute(
            """INSERT INTO games (game_id, home_team_id, away_team_id, game_date, season)
               VALUES (?, ?, ?, ?, ?)""",
            (game_id, home_team_id, away_team_id, game_date, season)
        )
        self.conn.commit()
        return game_id

    @staticmethod
    def parse_filename(filename: str) -> Optional[GameInfo]:
        """
        Parse CSV filename to extract game information

        Format: {AWAY}vs{HOME}_{GAMEID}_{TEAM}_{CATEGORY}_{SITUATION}.csv
        Example: BOSvsOTT_20149_Senators_Individual_5v5_1.csv

        Args:
            filename: CSV filename

        Returns:
            GameInfo object or None if parse fails
        """
        # Remove .csv extension
        name = filename.replace('.csv', '')

        # Pattern: {AWAY}vs{HOME}_{GAMEID}_{TEAM}_{CATEGORY}_{SITUATION}[_1|_2]
        # Updated to handle team abbrs with periods (N.J, S.J, L.A, T.B)
        pattern = r'^([A-Z][A-Z\.]+)vs([A-Z][A-Z\.]+)_(\d+)_([A-Za-z\.]+)_(.+?)_([A-Za-z0-9]+)(?:_([12]))?$'
        match = re.match(pattern, name)

        if not match:
            return None

        away, home, game_id, team, category_part, situation, file_type = match.groups()

        # Normalize team abbreviations (remove periods for consistency)
        # N.J -> NJ, S.J -> SJ, L.A -> LA, T.B -> TB
        away = away.replace('.', '')
        home = home.replace('.', '')
        team = team.replace('.', '')

        # Reconstruct category (may have underscores)
        # The category is everything between team name and situation
        # e.g., "Individual", "Forward_Lines", "On_Ice", "Shift_Report"
        return GameInfo(
            away_team=away,
            home_team=home,
            nst_game_id=game_id,
            team_name=team,
            category=category_part,
            situation=situation
        )

    @staticmethod
    def time_to_seconds(time_str: str) -> Optional[float]:
        """
        Convert time string to seconds

        Args:
            time_str: Time in format MM:SS or MM.decimal

        Returns:
            Time in seconds as float, or None if invalid
        """
        if not time_str or time_str == '-' or time_str == '':
            return None

        try:
            # Handle MM:SS format
            if ':' in time_str:
                parts = time_str.split(':')
                minutes = float(parts[0])
                seconds = float(parts[1]) if len(parts) > 1 else 0
                return minutes * 60 + seconds
            else:
                # Handle decimal minutes
                return float(time_str) * 60
        except (ValueError, AttributeError):
            return None

    @staticmethod
    def safe_float(value: Any) -> Optional[float]:
        """Safely convert value to float"""
        if value is None or value == '' or value == '-':
            return None
        try:
            return float(value)
        except (ValueError, TypeError):
            return None

    @staticmethod
    def safe_percentage(value: Any) -> Optional[float]:
        """
        Safely convert percentage value to decimal (0-1 scale)
        CSV percentages are stored as "XX.XX%" or "XX.XX", we convert to 0-1 for database
        """
        if value is None or value == '' or value == '-':
            return None
        try:
            # Remove '%' sign if present
            str_value = str(value).strip().replace('%', '')
            return float(str_value) / 100.0
        except (ValueError, TypeError):
            return None

    @staticmethod
    def safe_int(value: Any) -> int:
        """Safely convert value to int, return 0 if invalid"""
        if value is None or value == '' or value == '-':
            return 0
        try:
            return int(float(value))  # Handle "0.0" format
        except (ValueError, TypeError):
            return 0

    def import_player_stats(self, csv_path: str, game_id: str, team_id: int, situation_id: int):
        """
        Import individual player stats (skaters) from CSV

        Args:
            csv_path: Path to CSV file
            game_id: Game ID (TEXT - actual NHL game ID)
            team_id: Team ID
            situation_id: Situation ID
        """
        with open(csv_path, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)

            for row in reader:
                player_name = row.get('Player', '').strip()
                position = row.get('Position', '').strip()

                if not player_name or not position:
                    continue

                player_id = self.get_or_create_player(player_name, position)

                # Parse all stats
                data = {
                    'game_id': game_id,
                    'player_id': player_id,
                    'team_id': team_id,
                    'situation_id': situation_id,
                    'toi_seconds': self.time_to_seconds(row.get('TOI', '')),
                    'goals': self.safe_int(row.get('Goals', 0)),
                    'total_assists': self.safe_int(row.get('Total Assists', 0)),
                    'first_assists': self.safe_int(row.get('First Assists', 0)),
                    'second_assists': self.safe_int(row.get('Second Assists', 0)),
                    'total_points': self.safe_int(row.get('Total Points', 0)),
                    'shots': self.safe_int(row.get('Shots', 0)),
                    'shooting_pct': self.safe_percentage(row.get('SH%', None)),
                    'ixg': self.safe_float(row.get('ixG', 0)),
                    'icf': self.safe_int(row.get('iCF', 0)),
                    'iscf': self.safe_int(row.get('iSCF', 0)),
                    'ihdcf': self.safe_int(row.get('iHDCF', 0)),
                    'rush_attempts': self.safe_int(row.get('Rush Attempts', 0)),
                    'rebound_attempts': self.safe_int(row.get('Rebound Attempts', 0)),
                    'rebounds_created': self.safe_int(row.get('Rebounds Created', 0)),
                    'pim': self.safe_int(row.get('PIM', 0)),
                    'total_penalties': self.safe_int(row.get('Total Penalties', 0)),
                    'minor_penalties': self.safe_int(row.get('Minor', 0)),
                    'major_penalties': self.safe_int(row.get('Major', 0)),
                    'misconduct_penalties': self.safe_int(row.get('Misconduct', 0)),
                    'penalties_drawn': self.safe_int(row.get('Penalties Drawn', 0)),
                    'giveaways': self.safe_int(row.get('Giveaways', 0)),
                    'takeaways': self.safe_int(row.get('Takeaways', 0)),
                    'hits': self.safe_int(row.get('Hits', 0)),
                    'hits_taken': self.safe_int(row.get('Hits Taken', 0)),
                    'shots_blocked': self.safe_int(row.get('Shots Blocked', 0)),
                    'faceoffs_won': self.safe_int(row.get('Faceoffs Won', 0)),
                    'faceoffs_lost': self.safe_int(row.get('Faceoffs Lost', 0)),
                    'faceoff_pct': self.safe_percentage(row.get('Faceoffs %', None))
                }

                # Insert or replace
                self.cursor.execute("""
                    INSERT OR REPLACE INTO player_game_stats (
                        game_id, player_id, team_id, situation_id,
                        toi_seconds, goals, total_assists, first_assists, second_assists, total_points,
                        shots, shooting_pct, ixg, icf, iscf, ihdcf,
                        rush_attempts, rebound_attempts, rebounds_created,
                        pim, total_penalties, minor_penalties, major_penalties, misconduct_penalties, penalties_drawn,
                        giveaways, takeaways, hits, hits_taken, shots_blocked,
                        faceoffs_won, faceoffs_lost, faceoff_pct
                    ) VALUES (
                        :game_id, :player_id, :team_id, :situation_id,
                        :toi_seconds, :goals, :total_assists, :first_assists, :second_assists, :total_points,
                        :shots, :shooting_pct, :ixg, :icf, :iscf, :ihdcf,
                        :rush_attempts, :rebound_attempts, :rebounds_created,
                        :pim, :total_penalties, :minor_penalties, :major_penalties, :misconduct_penalties, :penalties_drawn,
                        :giveaways, :takeaways, :hits, :hits_taken, :shots_blocked,
                        :faceoffs_won, :faceoffs_lost, :faceoff_pct
                    )
                """, data)

        self.conn.commit()

